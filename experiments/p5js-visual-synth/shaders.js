(function (root) {
	const VERT = [
		'attribute vec3 aPosition;',
		'attribute vec2 aTexCoord;',
		'uniform mat4 uProjectionMatrix;',
		'uniform mat4 uModelViewMatrix;',
		'varying vec2 vTexCoord;',
		'void main() {',
		'  vTexCoord = aTexCoord;',
		'  gl_Position = uProjectionMatrix * uModelViewMatrix * vec4(aPosition, 1.0);',
		'}'
	].join('\n');

	const COMMON = [
		'varying vec2 vTexCoord;',
		'uniform vec2 u_resolution;',
		'uniform float u_time;',
		'uniform sampler2D u_camera;',
		'uniform float u_cameraEnabled;',
		'uniform float u_camOpacity;',
		'uniform float u_camIntensity;',
		'uniform float u_blendMode;',
		'',
		'vec3 hsv2rgb(vec3 c) {',
		'  vec3 rgb = clamp(abs(mod(c.x * 6.0 + vec3(0.0, 4.0, 2.0), 6.0) - 3.0) - 1.0, 0.0, 1.0);',
		'  return c.z * mix(vec3(1.0), rgb, c.y);',
		'}',
		'',
		'vec3 rgb2hsv(vec3 c) {',
		'  vec4 K = vec4(0.0, -1.0 / 3.0, 2.0 / 3.0, -1.0);',
		'  vec4 p = mix(vec4(c.bg, K.wz), vec4(c.gb, K.xy), step(c.b, c.g));',
		'  vec4 q = mix(vec4(p.xyw, c.r), vec4(c.r, p.yzx), step(p.x, c.r));',
		'  float d = q.x - min(q.w, q.y);',
		'  float e = 1.0e-10;',
		'  return vec3(abs(q.z + (q.w - q.y) / (6.0 * d + e)), d / (q.x + e), q.x);',
		'}',
		'',
		'vec3 applyHue(vec3 col, float hueDeg) {',
		'  vec3 hsv = rgb2hsv(col);',
		'  hsv.x = fract(hsv.x + hueDeg / 360.0);',
		'  return hsv2rgb(hsv);',
		'}',
		'',
		'vec2 screenUv() {',
		'  return vec2(vTexCoord.x, 1.0 - vTexCoord.y);',
		'}',
		'',
		'vec3 blendCamera(vec3 gen) {',
		'  if (u_cameraEnabled < 0.5) return gen;',
		'  vec3 cam = texture2D(u_camera, screenUv()).rgb * u_camIntensity;',
		'  float o = clamp(u_camOpacity, 0.0, 1.0);',
		'  if (u_blendMode < 0.5) {',
		'    return mix(gen, cam, o);',
		'  } else if (u_blendMode < 1.5) {',
		'    return clamp(gen + cam * o, 0.0, 1.0);',
		'  } else if (u_blendMode < 2.5) {',
		'    return gen * mix(vec3(1.0), cam, o);',
		'  }',
		'  return vec3(1.0) - (vec3(1.0) - gen) * (vec3(1.0) - cam * o);',
		'}'
	].join('\n');

	const WAVES = [
		COMMON,
		'uniform float u_frequency;',
		'uniform float u_amplitude;',
		'uniform float u_speed;',
		'uniform float u_direction;',
		'uniform float u_scale;',
		'',
		'void main() {',
		'  vec2 uv = screenUv() * 2.0 - 1.0;',
		'  uv.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  uv *= u_scale;',
		'  float ang = u_direction * 0.017453292;',
		'  vec2 dir = vec2(cos(ang), sin(ang));',
		'  vec2 perp = vec2(-dir.y, dir.x);',
		'  float t = u_time * u_speed;',
		'  float base = dot(uv, dir) * u_frequency;',
		'  float interfer = sin(dot(uv, perp) * u_frequency * 0.55 + t * 0.7) * u_amplitude;',
		'  float wave = sin(base + t + interfer * 1.4);',
		'  float wave2 = sin(base * 0.33 - t * 1.15 + interfer);',
		'  float v = 0.5 + 0.5 * wave;',
		'  vec3 c1 = vec3(0.02, 0.72, 0.92);',
		'  vec3 c2 = vec3(0.92, 0.12, 0.48);',
		'  vec3 col = mix(c1, c2, smoothstep(-0.15, 1.05, v));',
		'  float bands = smoothstep(0.02, 0.12, abs(wave));',
		'  col = mix(col * (0.18 + 0.82 * v), col, bands);',
		'  col += vec3(0.08, 0.03, 0.12) * (0.5 + 0.5 * wave2);',
		'  gl_FragColor = vec4(blendCamera(col), 1.0);',
		'}'
	].join('\n');

	const NOISE = [
		COMMON,
		'uniform float u_scale;',
		'uniform float u_speed;',
		'uniform float u_intensity;',
		'uniform float u_hue;',
		'uniform float u_mode;',
		'',
		'float hash(vec2 p) {',
		'  vec3 p3 = fract(vec3(p.xyx) * 0.1031);',
		'  p3 += dot(p3, p3.yzx + 33.33);',
		'  return fract((p3.x + p3.y) * p3.z);',
		'}',
		'',
		'float valueNoise(vec2 p) {',
		'  vec2 i = floor(p);',
		'  vec2 f = fract(p);',
		'  vec2 u = f * f * (3.0 - 2.0 * f);',
		'  float a = hash(i);',
		'  float b = hash(i + vec2(1.0, 0.0));',
		'  float c = hash(i + vec2(0.0, 1.0));',
		'  float d = hash(i + vec2(1.0, 1.0));',
		'  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);',
		'}',
		'',
		'float fbm(vec2 p) {',
		'  float v = 0.0;',
		'  float a = 0.5;',
		'  for (int i = 0; i < 5; i++) {',
		'    v += a * valueNoise(p);',
		'    p *= 2.03;',
		'    a *= 0.5;',
		'  }',
		'  return v;',
		'}',
		'',
		'void main() {',
		'  vec2 uv = screenUv();',
		'  uv.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  float t = u_time * u_speed;',
		'  vec2 p = uv * u_scale + vec2(t * 0.15, t * 0.22);',
		'  float n = fbm(p);',
		'  float n2 = fbm(p * 1.7 + 17.2);',
		'  vec3 col;',
		'  if (u_mode < 0.5) {',
		'    col = vec3(n);',
		'  } else {',
		'    float n3 = fbm(p.yx * 1.15 - 9.4);',
		'    col = vec3(n, n2, n3);',
		'    col = applyHue(col, u_hue);',
		'  }',
		'  col *= u_intensity;',
		'  gl_FragColor = vec4(blendCamera(col), 1.0);',
		'}'
	].join('\n');

	const PSYCHEDELIC = [
		COMMON,
		'uniform float u_speed;',
		'uniform float u_scale;',
		'uniform float u_distortion;',
		'uniform float u_intensity;',
		'uniform float u_hue;',
		'',
		'void main() {',
		'  vec2 uv = screenUv() * 2.0 - 1.0;',
		'  uv.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  uv *= u_scale;',
		'  float t = u_time * u_speed;',
		'  vec2 q = vec2(sin(uv.x * 2.2 + t), cos(uv.y * 2.0 - t * 0.8));',
		'  vec2 r = uv + u_distortion * vec2(',
		'    sin(uv.y * 3.1 + q.x + t * 1.3),',
		'    cos(uv.x * 2.7 + q.y - t)',
		'  );',
		'  float d = length(r);',
		'  vec3 col;',
		'  col.r = sin(d * 10.0 - t * 2.0) * 0.5 + 0.5;',
		'  col.g = cos(d * 8.0 - t * 1.5 + r.x) * 0.5 + 0.5;',
		'  col.b = sin(d * 12.0 - t * 2.5 + r.y) * 0.5 + 0.5;',
		'  col = applyHue(col, u_hue);',
		'  col *= u_intensity * 1.15;',
		'  gl_FragColor = vec4(blendCamera(clamp(col, 0.0, 1.0)), 1.0);',
		'}'
	].join('\n');

	root.SYNTH_SHADERS = {
		vert: VERT,
		waves: WAVES,
		noise: NOISE,
		psychedelic: PSYCHEDELIC
	};
})(window);
