(function (root) {
	const VERT = [
		'attribute vec3 aPosition;',
		'attribute vec2 aTexCoord;',
		'uniform mat4 uProjectionMatrix;',
		'uniform mat4 uModelViewMatrix;',
		'varying vec2 vTexCoord;',
		'void main() {',
		'  vTexCoord = aTexCoord;',
		'  gl_Position = uProjectionMatrix * uModelViewMatrix * vec4(aPosition, 1.0);',
		'}'
	].join('\n');

	const FILTER = [
		'varying vec2 vTexCoord;',
		'uniform vec2 u_resolution;',
		'uniform float u_time;',
		'uniform sampler2D u_input;',
		'',
		'vec2 uv() {',
		'  return vTexCoord;',
		'}',
		'',
		'vec4 src() {',
		'  return texture2D(u_input, uv());',
		'}'
	].join('\n');

	const BLEND_FN = [
		'uniform sampler2D u_input;',
		'uniform float u_hasInput;',
		'uniform float u_blendMode;',
		'',
		'vec3 blendWith(vec3 gen) {',
		'  if (u_hasInput < 0.5) return gen;',
		'  vec3 prev = texture2D(u_input, vTexCoord).rgb;',
		'  if (u_blendMode < 0.5) return gen;',
		'  if (u_blendMode < 1.5) return min(prev + gen, 1.0);',
		'  if (u_blendMode < 2.5) return prev * gen;',
		'  if (u_blendMode < 3.5) return vec3(1.0) - (vec3(1.0) - prev) * (vec3(1.0) - gen);',
		'  if (u_blendMode < 4.5) return abs(prev - gen);',
		'  if (u_blendMode < 5.5) {',
		'    vec3 low = 2.0 * prev * gen;',
		'    vec3 high = vec3(1.0) - 2.0 * (vec3(1.0) - prev) * (vec3(1.0) - gen);',
		'    return mix(low, high, step(0.5, prev));',
		'  }',
		'  if (u_blendMode < 6.5) return max(prev - gen, 0.0);',
		'  if (u_blendMode < 7.5) return max(prev, gen);',
		'  return min(prev, gen);',
		'}'
	].join('\n');

	const LINES = [
		'varying vec2 vTexCoord;',
		'uniform vec2 u_resolution;',
		'uniform float u_fuzzyness;',
		'uniform float u_amount;',
		'uniform float u_width;',
		'uniform float u_rotation;',
		'uniform float u_position;',
		'uniform vec3 u_color;',
		BLEND_FN,
		'',
		'void main() {',
		'  vec2 p = vTexCoord * 2.0 - 1.0;',
		'  p.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  float ang = u_rotation * 0.017453292;',
		'  vec2 dir = vec2(sin(ang), cos(ang));',
		'  float n = u_amount;',
		'  float coord = dot(p, dir) * 0.5 + 0.5 + u_position;',
		'  float g = abs(fract(coord * max(n, 1.0)) - 0.5) * 2.0;',
		'  float halfW = clamp(u_width, 0.0, 1.0);',
		'  float fuzz = mix(0.003, 0.5, clamp(u_fuzzyness, 0.0, 1.0));',
		'  float v = (1.0 - smoothstep(halfW, halfW + fuzz, g)) * step(0.5, n);',
		'  gl_FragColor = vec4(blendWith(u_color * v), 1.0);',
		'}'
	].join('\n');

	const NOISE = [
		'varying vec2 vTexCoord;',
		'uniform vec2 u_resolution;',
		'uniform float u_time;',
		'uniform float u_scale;',
		'uniform vec3 u_translate;',
		'uniform float u_speed;',
		'uniform float u_octaves;',
		'uniform float u_contrast;',
		BLEND_FN,
		'',
		'float hash(vec3 p) {',
		'  p = fract(p * 0.1031);',
		'  p += dot(p, p.zyx + 33.33);',
		'  return fract((p.x + p.y) * p.z);',
		'}',
		'',
		'float valueNoise(vec3 p) {',
		'  vec3 i = floor(p);',
		'  vec3 f = fract(p);',
		'  vec3 u = f * f * (3.0 - 2.0 * f);',
		'  return mix(',
		'    mix(',
		'      mix(hash(i), hash(i + vec3(1.0, 0.0, 0.0)), u.x),',
		'      mix(hash(i + vec3(0.0, 1.0, 0.0)), hash(i + vec3(1.0, 1.0, 0.0)), u.x),',
		'      u.y',
		'    ),',
		'    mix(',
		'      mix(hash(i + vec3(0.0, 0.0, 1.0)), hash(i + vec3(1.0, 0.0, 1.0)), u.x),',
		'      mix(hash(i + vec3(0.0, 1.0, 1.0)), hash(i + vec3(1.0, 1.0, 1.0)), u.x),',
		'      u.y',
		'    ),',
		'    u.z',
		'  );',
		'}',
		'',
		'float fbm(vec3 p) {',
		'  float sum = 0.0;',
		'  float amp = 0.5;',
		'  float norm = 0.0;',
		'  for (int i = 0; i < 6; i++) {',
		'    float gate = step(float(i), u_octaves - 0.5);',
		'    sum += valueNoise(p) * amp * gate;',
		'    norm += amp * gate;',
		'    p *= 2.03;',
		'    amp *= 0.5;',
		'  }',
		'  return sum / max(norm, 0.001);',
		'}',
		'',
		'void main() {',
		'  vec2 p = vTexCoord;',
		'  p.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  float t = u_time * u_speed;',
		'  vec3 q = vec3(p * u_scale, 0.0) + u_translate + vec3(t * 0.31, t * 0.17, t * 0.13);',
		'  q.xy += 0.35 * vec2(valueNoise(q + t), valueNoise(q.yxz - t));',
		'  float v = fbm(q);',
		'  v = clamp(pow(max(v, 0.0), 1.0 / max(u_contrast, 0.08)), 0.0, 1.0);',
		'  gl_FragColor = vec4(blendWith(vec3(v)), 1.0);',
		'}'
	].join('\n');

	const CAMERA = [
		'varying vec2 vTexCoord;',
		'uniform vec2 u_resolution;',
		'uniform sampler2D u_video;',
		BLEND_FN,
		'',
		'void main() {',
		'  vec3 cam = texture2D(u_video, vTexCoord).rgb;',
		'  gl_FragColor = vec4(blendWith(cam), 1.0);',
		'}'
	].join('\n');

	const KALEIDOSCOPE = [
		FILTER,
		'uniform float u_segments;',
		'uniform float u_angle;',
		'uniform float u_zoom;',
		'uniform float u_offsetX;',
		'uniform float u_offsetY;',
		'',
		'void main() {',
		'  vec2 uv = vTexCoord - 0.5;',
		'  uv.x *= u_resolution.x / max(u_resolution.y, 1.0);',
		'  uv -= vec2(u_offsetX, u_offsetY) - 0.5;',
		'  float ang = u_angle * 0.017453292;',
		'  float c = cos(ang);',
		'  float s = sin(ang);',
		'  uv = vec2(c * uv.x - s * uv.y, s * uv.x + c * uv.y);',
		'  float r = length(uv);',
		'  float a = atan(uv.y, uv.x);',
		'  float slices = max(u_segments, 2.0);',
		'  float ta = 3.14159265 / slices;',
		'  a = mod(a, ta * 2.0);',
		'  a = abs(a - ta);',
		'  vec2 st = vec2(cos(a), sin(a)) * r / max(u_zoom, 0.05);',
		'  st.x /= u_resolution.x / max(u_resolution.y, 1.0);',
		'  st += 0.5;',
		'  st = abs(fract(st * 0.5 + 0.5) * 2.0 - 1.0);',
		'  gl_FragColor = texture2D(u_input, st);',
		'}'
	].join('\n');

	const WARP = [
		FILTER,
		'uniform float u_amount;',
		'uniform float u_frequency;',
		'uniform float u_speed;',
		'uniform float u_detail;',
		'',
		'void main() {',
		'  vec2 st = uv();',
		'  float t = u_time * u_speed;',
		'  vec2 q = st;',
		'  q += u_amount * 0.22 * vec2(',
		'    sin(st.y * u_frequency + t),',
		'    cos(st.x * u_frequency * 0.91 - t)',
		'  );',
		'  q += u_amount * u_detail * 0.12 * vec2(',
		'    sin(q.y * u_frequency * 2.15 - t * 1.3),',
		'    cos(q.x * u_frequency * 1.87 + t * 1.1)',
		'  );',
		'  gl_FragColor = texture2D(u_input, clamp(q, 0.0, 1.0));',
		'}'
	].join('\n');

	const LOOKUP = [
		FILTER,
		'uniform sampler2D u_lut;',
		'uniform float u_hue;',
		'uniform float u_saturation;',
		'uniform float u_exposure;',
		'',
		'vec3 rgb2hsv(vec3 c) {',
		'  vec4 K = vec4(0.0, -1.0 / 3.0, 2.0 / 3.0, -1.0);',
		'  vec4 p = mix(vec4(c.bg, K.wz), vec4(c.gb, K.xy), step(c.b, c.g));',
		'  vec4 q = mix(vec4(p.xyw, c.r), vec4(c.r, p.yzx), step(p.x, c.r));',
		'  float d = q.x - min(q.w, q.y);',
		'  float e = 1.0e-10;',
		'  return vec3(abs(q.z + (q.w - q.y) / (6.0 * d + e)), d / (q.x + e), q.x);',
		'}',
		'',
		'vec3 hsv2rgb(vec3 c) {',
		'  vec4 K = vec4(1.0, 2.0 / 3.0, 1.0 / 3.0, 3.0);',
		'  vec3 p = abs(fract(c.xxx + K.xyz) * 6.0 - K.www);',
		'  return c.z * mix(K.xxx, clamp(p - K.xxx, 0.0, 1.0), c.y);',
		'}',
		'',
		'void main() {',
		'  vec3 col = src().rgb;',
		'  float luma = dot(col, vec3(0.299, 0.587, 0.114));',
		'  vec3 mapped = texture2D(u_lut, vec2(clamp(luma, 0.0, 1.0), 0.5)).rgb;',
		'  vec3 hsv = rgb2hsv(mapped);',
		'  hsv.x = fract(hsv.x + u_hue / 360.0);',
		'  hsv.y = clamp(hsv.y * u_saturation, 0.0, 1.0);',
		'  mapped = hsv2rgb(hsv) * u_exposure;',
		'  gl_FragColor = vec4(clamp(mapped, 0.0, 1.0), 1.0);',
		'}'
	].join('\n');

	const BLOOM_BRIGHT = [
		FILTER,
		'uniform float u_threshold;',
		'',
		'void main() {',
		'  vec3 col = src().rgb;',
		'  float luma = dot(col, vec3(0.2126, 0.7152, 0.0722));',
		'  float knee = max(u_threshold * 0.5, 0.001);',
		'  float soft = luma - u_threshold + knee;',
		'  soft = clamp(soft, 0.0, 2.0 * knee);',
		'  soft = (soft * soft) / (4.0 * knee);',
		'  float contrib = max(soft, luma - u_threshold) / max(luma, 1.0e-4);',
		'  gl_FragColor = vec4(col * contrib, 1.0);',
		'}'
	].join('\n');

	const BLOOM_DOWN = [
		FILTER,
		'uniform vec2 u_texel;',
		'uniform float u_offset;',
		'',
		'void main() {',
		'  vec2 st = uv();',
		'  vec2 halfpixel = u_texel * u_offset;',
		'  vec3 sum = texture2D(u_input, st).rgb * 4.0;',
		'  sum += texture2D(u_input, st - halfpixel).rgb;',
		'  sum += texture2D(u_input, st + halfpixel).rgb;',
		'  sum += texture2D(u_input, st + vec2(halfpixel.x, -halfpixel.y)).rgb;',
		'  sum += texture2D(u_input, st - vec2(halfpixel.x, -halfpixel.y)).rgb;',
		'  gl_FragColor = vec4(sum / 8.0, 1.0);',
		'}'
	].join('\n');

	const BLOOM_UP = [
		FILTER,
		'uniform vec2 u_texel;',
		'uniform float u_offset;',
		'',
		'void main() {',
		'  vec2 st = uv();',
		'  vec2 halfpixel = u_texel * u_offset;',
		'  vec3 sum = texture2D(u_input, st + vec2(-halfpixel.x * 2.0, 0.0)).rgb;',
		'  sum += texture2D(u_input, st + vec2(-halfpixel.x, halfpixel.y)).rgb * 2.0;',
		'  sum += texture2D(u_input, st + vec2(0.0, halfpixel.y * 2.0)).rgb;',
		'  sum += texture2D(u_input, st + vec2(halfpixel.x, halfpixel.y)).rgb * 2.0;',
		'  sum += texture2D(u_input, st + vec2(halfpixel.x * 2.0, 0.0)).rgb;',
		'  sum += texture2D(u_input, st + vec2(halfpixel.x, -halfpixel.y)).rgb * 2.0;',
		'  sum += texture2D(u_input, st + vec2(0.0, -halfpixel.y * 2.0)).rgb;',
		'  sum += texture2D(u_input, st + vec2(-halfpixel.x, -halfpixel.y)).rgb * 2.0;',
		'  gl_FragColor = vec4(sum / 12.0, 1.0);',
		'}'
	].join('\n');

	const BLOOM_COMP = [
		FILTER,
		'uniform sampler2D u_bloom;',
		'uniform float u_intensity;',
		'',
		'void main() {',
		'  vec3 col = src().rgb;',
		'  vec3 glow = texture2D(u_bloom, uv()).rgb * u_intensity;',
		'  vec3 add = col + glow;',
		'  vec3 screen = vec3(1.0) - (vec3(1.0) - col) * (vec3(1.0) - glow);',
		'  gl_FragColor = vec4(mix(add, screen, 0.55), 1.0);',
		'}'
	].join('\n');

	const EDGE = [
		FILTER,
		'uniform float u_threshold;',
		'uniform float u_intensity;',
		'uniform float u_radius;',
		'uniform float u_mix;',
		'uniform float u_invert;',
		'',
		'float lumaAt(vec2 st) {',
		'  vec3 col = texture2D(u_input, clamp(st, 0.0, 1.0)).rgb;',
		'  return dot(col, vec3(0.299, 0.587, 0.114));',
		'}',
		'',
		'void main() {',
		'  vec2 st = uv();',
		'  vec2 texel = (1.0 / max(u_resolution, vec2(1.0))) * max(u_radius, 0.15);',
		'  float tl = lumaAt(st + vec2(-texel.x, -texel.y));',
		'  float t  = lumaAt(st + vec2(0.0, -texel.y));',
		'  float tr = lumaAt(st + vec2(texel.x, -texel.y));',
		'  float l  = lumaAt(st + vec2(-texel.x, 0.0));',
		'  float r  = lumaAt(st + vec2(texel.x, 0.0));',
		'  float bl = lumaAt(st + vec2(-texel.x, texel.y));',
		'  float b  = lumaAt(st + vec2(0.0, texel.y));',
		'  float br = lumaAt(st + vec2(texel.x, texel.y));',
		'  float gx = -tl + tr - 2.0 * l + 2.0 * r - bl + br;',
		'  float gy = -tl - 2.0 * t - tr + bl + 2.0 * b + br;',
		'  float mag = length(vec2(gx, gy));',
		'  float edge = clamp((mag - u_threshold) * u_intensity, 0.0, 1.0);',
		'  edge = mix(edge, 1.0 - edge, clamp(u_invert, 0.0, 1.0));',
		'  vec3 srcCol = src().rgb;',
		'  gl_FragColor = vec4(mix(srcCol, vec3(edge), clamp(u_mix, 0.0, 1.0)), 1.0);',
		'}'
	].join('\n');

	const COPY = [
		FILTER,
		'uniform float u_gain;',
		'',
		'void main() {',
		'  gl_FragColor = vec4(src().rgb * u_gain, 1.0);',
		'}'
	].join('\n');

	root.SYNTH_SHADERS = {
		vert: VERT,
		lines: LINES,
		noise: NOISE,
		camera: CAMERA,
		warp: WARP,
		lookup: LOOKUP,
		kaleidoscope: KALEIDOSCOPE,
		bloomBright: BLOOM_BRIGHT,
		bloomDown: BLOOM_DOWN,
		bloomUp: BLOOM_UP,
		bloomComp: BLOOM_COMP,
		edge: EDGE,
		copy: COPY
	};
})(window);
