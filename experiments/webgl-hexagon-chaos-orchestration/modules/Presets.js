export const PRESET_NAMES = Object.keys(PRESETS);

/**
 * Apply a preset patch onto `params`.
 * Keys missing from the patch fall back to the canonical defaults so each
 * preset can be authored as a partial without surprise carryover from the
 * previous preset.
 */
export function applyPresetToParams(params, name) {
	const patch = PRESETS[name];
	if (!patch) return;

	// Preserve params not authored by presets (system, debug, paused...).
	const keepKeys = ['preset', 'resolutionScale', 'fpsLimit', 'debugView', 'paused'];
	const preserved = {};
	for (const k of keepKeys) preserved[k] = params[k];

	Object.assign(params, DEFAULT_PARAMS, patch);
	Object.assign(params, preserved);
	params.preset = name;
}
